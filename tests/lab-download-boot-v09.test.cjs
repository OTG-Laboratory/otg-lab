// OTG! LAB v0.9 static and tamper-safety checks; no user data is touched.
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.join(__dirname,'..');
const json=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const pack=fs.readFileSync(path.join(root,'catalogue-packs/fh5-complete-1.0.0.json'));
const manifest=json('catalogue-packs/library-v1.json').packs[0];
const sha=crypto.createHash('sha256').update(pack).digest('hex');
assert.equal(sha,manifest.sha256,'pack pinned digest');
const doc=json('js/otg-lab-boot-manifest-v09.json');
assert.equal(doc.scripts.length,137,'original scripts all present');
assert.equal(new Set(doc.scripts).size,137,'no duplicated script imports');
assert(doc.scripts.some(x=>x.includes('lab09-network-cars')));
assert(doc.scripts.some(x=>x.includes('lab081-sticky-delete')));
assert(doc.scripts.indexOf('js/fh5-catalogue-v6069-main.js?v=lab09-network-cars')>0);
assert(doc.scripts.indexOf('js/fh5-catalogue-v6069-main.js?v=lab09-network-cars')<doc.scripts.findIndex(x=>x.includes('catalogue-deterministic-v6110')));
const source=fs.readFileSync(path.join(root,'js/fh5-catalogue-v6069-main.js'),'utf8');
assert(!source.includes('const FH5_CATALOGUE=['),'master car data not embedded');
assert(source.includes('const FH5_CATALOGUE=window.OTG_LAB_VERIFIED_FH5_CARS_V09'));
const loader=fs.readFileSync(path.join(root,'js/otg-lab-download-boot-v09.js'),'utf8');
assert(loader.includes(`const PIN='${sha}'`),'SHA pinned independently');
assert(loader.includes('document.dispatchEvent(new Event(\'DOMContentLoaded\'))'));
assert(loader.includes('window.dispatchEvent(new Event(\'load\'))'));
assert.equal(json('update-manifest.json').labVersion,'0.9');
assert(fs.readFileSync(path.join(root,'index.html'),'utf8').includes('DEVELOPMENT COPY · v0.9'));
const rows=JSON.parse(pack).cars;
assert.equal(rows.length,902);
for(let i=0;i<rows.length;i++)assert.equal(rows[i].catalogueId,'fh5-v1-'+String(i+1).padStart(4,'0'));
console.log('PASS: v0.9 downloaded-catalogue bootstrap source & identity checks (12 assertions groups)');
